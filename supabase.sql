create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 5 and 80),
  deal text not null check (deal in ('sale','rent')),
  kind text not null,
  city text not null,
  area text not null,
  price numeric not null check (price > 0),
  rent_period text check (rent_period in ('month','year')),
  size_m2 numeric not null check (size_m2 > 0),
  rooms int check (rooms >= 0),
  baths int check (baths >= 0),
  floor int check (floor >= 0),
  description text,
  lat double precision not null,
  lng double precision not null,
  images text[] not null default '{}',
  featured boolean not null default false,
  status text not null default 'available' check (status in ('available','sold','rented')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where email = auth.jwt() ->> 'email');
$$;

create or replace function public.touch() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists listings_touch on public.listings;
create trigger listings_touch before update on public.listings for each row execute function public.touch();

alter table public.admins enable row level security;
alter table public.listings enable row level security;

drop policy if exists "public read" on public.listings;
drop policy if exists "admin insert" on public.listings;
drop policy if exists "admin update" on public.listings;
drop policy if exists "admin delete" on public.listings;
create policy "public read"  on public.listings for select using (true);
create policy "admin insert" on public.listings for insert with check (public.is_admin());
create policy "admin update" on public.listings for update using (public.is_admin()) with check (public.is_admin());
create policy "admin delete" on public.listings for delete using (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.listings to anon, authenticated;
grant insert, update, delete on public.listings to authenticated;
revoke all on public.admins from anon, authenticated;

